    }

    fun detectionErrorMessage(reason: DetectionErrorReason): String = when (reason) {
        DetectionErrorReason.EMPTY_URL ->
            if (isBangla) "অনুগ্রহ করে একটি ছবির URL দিন।" else "Please enter an image URL."
        DetectionErrorReason.INVALID_URL_FORMAT ->
            if (isBangla) "অবৈধ URL। http:// বা https:// দিয়ে শুরু হওয়া সঠিক লিংক দিন।" else "Invalid URL. Enter a valid http:// or https:// URL."
        DetectionErrorReason.UNSAFE_OR_LOCAL_URL ->
            if (isBangla) "নিরাপত্তার কারণে লোকাল বা প্রাইভেট নেটওয়ার্ক ঠিকানা ব্লক করা হয়েছে।" else "Local or private network URLs are blocked for security."
        DetectionErrorReason.NO_NUMERIC_PAGE_FOUND ->
            if (isBangla) "URL-এ পৃষ্ঠা নম্বর শনাক্ত করা যায়নি। নম্বরসহ ছবির URL দিন।" else "Unable to detect a page number in this URL."
    }

    fun statusReasonMessage(status: PageScanStatus, httpCode: Int?, detail: String?): String = when (status) {
        PageScanStatus.MISSING ->
            if (isBangla) "নিশ্চিতভাবে পৃষ্ঠাটি পাওয়া যায়নি (HTTP ${httpCode ?: 404})।"
            else "Missing page confirmed (HTTP ${httpCode ?: 404})."
        PageScanStatus.BLOCKED ->
            if (isBangla) "উৎস ওয়েবসাইট অ্যাক্সেস ব্লক করেছে (HTTP ${httpCode ?: 403})। স্ক্যান বিরতিতে রাখা হয়েছে।"
            else "Source website blocked access (HTTP ${httpCode ?: 403}). Scanning paused."
        PageScanStatus.RATE_LIMITED ->
            if (isBangla) "সার্ভার অনুরোধের সীমা অতিক্রম করেছে (HTTP 429)। কিছুক্ষণ পর আবার চেষ্টা করুন।"
            else "Server rate limit reached (HTTP 429). Wait briefly and resume."
        PageScanStatus.SERVER_ERROR ->
            if (isBangla) "সার্ভার সাময়িকভাবে অনুপলব্ধ (HTTP ${httpCode ?: 500})। আবার চেষ্টা বা রিজিউম করুন।"
            else "Server temporarily unavailable (HTTP ${httpCode ?: 500}). Retry or resume."
        PageScanStatus.TIMEOUT ->
            if (isBangla) "অনুরোধের সময়সীমা শেষ হয়েছে। সংযোগ পরীক্ষা করে রিজিউম করুন।"
            else "Request timed out. Check connection and resume."
        PageScanStatus.NETWORK_ERROR ->
            if (isBangla) "নেটওয়ার্ক সংযোগে ত্রুটি: ${detail ?: "সংযোগ বিচ্ছিন্ন"}।"
            else "Network connection failure: ${detail ?: "Unable to reach host"}."
        PageScanStatus.INVALID_IMAGE ->
            if (isBangla) "HTTP 200 পাওয়া গেছে, কিন্তু এটি বৈধ JPG ছবি নয় (সম্ভবত HTML ত্রুটি পৃষ্ঠা)।"
            else "Response is not a valid JPEG image (possibly an HTML error page)."
        PageScanStatus.VALID ->
            if (isBangla) "বৈধ JPG ছবি" else "Valid JPEG image"
    }
}


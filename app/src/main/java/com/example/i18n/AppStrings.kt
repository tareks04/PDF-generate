    fun runStateLabel(state: ScannerRunState): String = when (state) {
        ScannerRunState.IDLE -> if (isBangla) "প্রস্তুত" else "Idle"
        ScannerRunState.SCANNING -> if (isBangla) "স্ক্যান চলছে..." else "Scanning..."
